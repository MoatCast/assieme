WIDTH, HEIGHT = 16, 18  # every pose is padded to this box, feet on the bottom row


def grid(s):
    return [r for r in s.strip('\n').split('\n')]


BUBBLE = grid("""
.RRR.
RRWRR
RRWRR
RRRRR
RRWRR
.RRR.
R....
""")


def hand(rest, arm, head):
    """The rest pose with one hand raised at column `arm` and the "!" bubble: what "needs you" looks like."""
    top = max(0, 2 - head)  # room above the head for the raised hand
    w = max(len(r) for r in rest)
    rows = [list('.' * max(w, 16)) for _ in range(top)] + [list(r.ljust(max(w, 16), '.')) for r in rest]
    head += top
    rows[head - 2][arm:arm + 2] = 'RR'
    rows[head - 1][arm:arm + 2] = 'RR'
    rows[head][arm] = 'L'
    for y in range(head + 1, head + 5):
        rows[y][arm] = 'M'
    for j, line in enumerate(BUBBLE):
        for i, ch in enumerate(line):
            if ch != '.':
                rows[j][11 + i] = ch
    return [''.join(r) for r in rows]


