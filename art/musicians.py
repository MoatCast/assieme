def pad(g):
    """Bottom-aligned in the WIDTH x HEIGHT box, so musicians of every instrument line up in a row."""
    rows = [r.ljust(WIDTH, '.') for r in g]
    assert len(rows) <= HEIGHT and all(len(r) == WIDTH for r in rows), g
    return ['.' * WIDTH] * (HEIGHT - len(rows)) + rows


