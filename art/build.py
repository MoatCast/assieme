"""Writes app/src/musicians.gen.ts from art/musicians.py: the grids as rows of letters, and each letter's colour token.
Run it after changing the art: python3 art/build.py (a test fails while the generated file is out of date)."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import musicians  # noqa: E402

OUT = os.path.join(HERE, '..', 'app', 'src', 'musicians.gen.ts')
# R is the app's own "needs you" colour: coral means the same here as everywhere else.
TOKENS = {k: f'--quiet-musician-{k.lower()}' for k in musicians.LETTERS} | {'R': '--quiet-needs-you'}


def module():
    rows = lambda g: json.dumps(g)  # noqa: E731
    out = ['// Generated by art/build.py from art/musicians.py. Edit the art there, then run: python3 art/build.py',
           '',
           f'export const INSTRUMENTS = {json.dumps(musicians.INSTRUMENTS)} as const;',
           'export type Instrument = (typeof INSTRUMENTS)[number];',
           f'export const WIDTH = {musicians.WIDTH};',
           f'export const HEIGHT = {musicians.HEIGHT};',
           f'export const LETTERS: Record<string, string> = {json.dumps(TOKENS)};',
           'export const SPRITES: Record<Instrument, { play: [string[], string[]]; rest: string[]; hand: string[] }> = {']
    for name in musicians.INSTRUMENTS:
        s = musicians.SPRITES[name]
        out.append(f'  {name}: {{ play: [{rows(s["play"][0])}, {rows(s["play"][1])}], rest: {rows(s["rest"])}, '
                   f'hand: {rows(s["hand"])} }},')
    w = max(map(len, musicians.CONDUCTOR))
    out += ['};', f'export const CONDUCTOR: string[] = {rows([r.ljust(w, ".") for r in musicians.CONDUCTOR])};', '']
    return '\n'.join(out)


if __name__ == '__main__':
    path = sys.argv[1] if len(sys.argv) > 1 else OUT
    with open(path, 'w') as f:
        f.write(module())
